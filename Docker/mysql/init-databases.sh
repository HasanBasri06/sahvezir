#!/bin/bash
# İlk başlatmada (boş volume) çalışır: her proje için ayrı veritabanı ve kullanıcı oluşturur.
set -e
mysql -uroot -p"${MYSQL_ROOT_PASSWORD}" <<SQL
CREATE DATABASE IF NOT EXISTS \`${BIMILYONCU_DB_DATABASE}\` CHARACTER SET utf8mb4 COLLATE utf8mb4_unicode_ci;
CREATE USER IF NOT EXISTS '${BIMILYONCU_DB_USERNAME}'@'%' IDENTIFIED BY '${BIMILYONCU_DB_PASSWORD}';
GRANT ALL PRIVILEGES ON \`${BIMILYONCU_DB_DATABASE}\`.* TO '${BIMILYONCU_DB_USERNAME}'@'%';

CREATE DATABASE IF NOT EXISTS \`${LOGISTICS_DB_DATABASE}\` CHARACTER SET utf8mb4 COLLATE utf8mb4_unicode_ci;
CREATE USER IF NOT EXISTS '${LOGISTICS_DB_USERNAME}'@'%' IDENTIFIED BY '${LOGISTICS_DB_PASSWORD}';
GRANT ALL PRIVILEGES ON \`${LOGISTICS_DB_DATABASE}\`.* TO '${LOGISTICS_DB_USERNAME}'@'%';
FLUSH PRIVILEGES;
SQL
